//
//  Closed-caption lyrics fallback for YouTube tracks when LRCLIB has no
//  match. YouTube's timedtext endpoint requires a proof-of-origin token
//  minted inside the player (direct fetches return HTTP 200 with an empty
//  body), so this client never touches YouTube endpoints itself — the raw
//  fmt=json3 body arrives through the injected closure, which replays the
//  player's own authorized request from inside the page. See
//  BrowserTabPoller.fetchCaptionJSON for the capture sequence.
//
//  Uses async/await per AGENTS.md §5. Pure rank/parse/clean functions are
//  unit-tested in Tests/test_youtube_captions.swift.
//

import Foundation

/// One caption track option surfaced by the in-page context probe.
struct CaptionTrackOption: Sendable, Equatable {
    let languageCode: String
    /// "asr" for auto-generated tracks, nil for manually uploaded ones.
    let kind: String?

    var isAutoGenerated: Bool { kind == "asr" }
}

/// Fetches and parses YouTube closed captions as a lyrics source.
final class YouTubeCaptionsClient: Sendable {

    /// Returns the raw fmt=json3 caption body for a video ID, or nil when
    /// capture fails. Injected so tests can stub the page/AppleScript layer.
    private let fetchCaptionJSON: @Sendable (String) async -> String?

    init(fetchCaptionJSON: @escaping @Sendable (String) async -> String?) {
        self.fetchCaptionJSON = fetchCaptionJSON
    }

    /// Returns parsed lines plus generated LRC text, or nil when captions
    /// are unavailable (no tracks, capture failed, unparsable body, or the
    /// body holds no lyric-bearing lines).
    func fetchLyrics(videoId: String) async -> (lines: [LRCLine], rawLRC: String)? {
        guard let json = await fetchCaptionJSON(videoId),
              !json.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              let lines = Self.parseJSON3(json),
              !lines.isEmpty else { return nil }
        return (lines, Self.makeLRC(from: lines))
    }

    /// Chooses a track: manual English → auto English → manual other →
    /// auto other. Auto-translated tracks never appear in the player's base
    /// track list, so no filtering is needed. Ties keep list order.
    static func chooseTrack(from tracks: [CaptionTrackOption]) -> CaptionTrackOption? {
        func rank(_ track: CaptionTrackOption) -> Int {
            let english = track.languageCode.lowercased().hasPrefix("en")
            switch (english, track.isAutoGenerated) {
            case (true, false): return 0
            case (true, true): return 1
            case (false, false): return 2
            case (false, true): return 3
            }
        }
        return tracks.min { rank($0) < rank($1) }
    }

    /// Parses a fmt=json3 caption body into timestamped lines.
    /// Returns nil for malformed bodies or bodies with no lyric lines.
    static func parseJSON3(_ json: String) -> [LRCLine]? {
        guard let data = json.data(using: .utf8),
              let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let events = root["events"] as? [[String: Any]] else { return nil }

        var lines: [LRCLine] = []
        for event in events {
            let startMs: Double?
            if let value = event["tStartMs"] as? Double {
                startMs = value
            } else if let value = event["tStartMs"] as? Int {
                startMs = Double(value)
            } else {
                continue
            }
            let segs = event["segs"] as? [[String: Any]] ?? []
            let raw = segs.compactMap { $0["utf8"] as? String }.joined()
            guard let start = startMs, let text = cleanCaptionText(raw) else { continue }
            lines.append(LRCLine(timestamp: start / 1000.0, text: text))
        }
        return lines.isEmpty ? nil : lines
    }

    /// Cleans one caption event's text. Returns nil for non-lyric events.
    /// Drops bracket-only annotations ([Music], [Applause]) but keeps
    /// parenthesized backing vocals ("(ooh)"), which manual music captions
    /// use legitimately. Strips ">>" continuations and "NAME:" prefixes.
    static func cleanCaptionText(_ raw: String) -> String? {
        var text = raw
            .replacingOccurrences(of: "\n", with: " ")
            .components(separatedBy: .whitespaces)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        guard !text.isEmpty else { return nil }

        if text.hasPrefix("[") && text.hasSuffix("]") { return nil }

        if text.hasPrefix(">>") {
            text = String(text.dropFirst(2)).trimmingCharacters(in: .whitespaces)
            guard !text.isEmpty else { return nil }
        }

        if let colon = text.firstIndex(of: ":") {
            let prefix = text[..<colon]
            let isSpeakerTag = !prefix.isEmpty
                && !prefix.contains(" ")
                && prefix.rangeOfCharacter(from: .letters) != nil
                && prefix == prefix.uppercased()
            if isSpeakerTag {
                text = String(text[text.index(after: colon)...]).trimmingCharacters(in: .whitespaces)
                guard !text.isEmpty else { return nil }
            }
        }

        return text
    }

    /// Computes the seconds to shift album-timed LRC lines so they match a
    /// music video's timeline, using caption timestamps as video-relative
    /// ground truth. Music videos often open with dialogue/skits (the
    /// Rocketeer video runs ~25s longer than its lyrics), shifting every
    /// line by a constant offset.
    ///
    /// Compares first lyric-bearing lines; returns nil when the texts don't
    /// match (wrong-video guard), the shift is negligible (< 0.5s), or
    /// implausibly large (> 90s).
    static func calibrationOffset(lrclib lines: [LRCLine], captions: [LRCLine]) -> TimeInterval? {
        func firstLyric(_ lines: [LRCLine]) -> LRCLine? {
            lines.first { !$0.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
        }
        guard let lrc = firstLyric(lines), let cap = firstLyric(captions),
              normalizeLyric(lrc.text) == normalizeLyric(cap.text) else { return nil }
        let offset = cap.timestamp - lrc.timestamp
        guard abs(offset) >= 0.5, abs(offset) <= 90 else { return nil }
        return offset
    }

    /// Normalizes lyric text for cross-source comparison: case, punctuation,
    /// and spacing differences between LRCLIB transcriptions and captions
    /// must not block a match.
    static func normalizeLyric(_ text: String) -> String {
        text.lowercased()
            .components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }

    /// Renders lines as LRC text so caption results reuse the synced cache
    /// state and sync engine with no format plumbing.
    static func makeLRC(from lines: [LRCLine]) -> String {
        lines.map { line in
            let total = max(0, line.timestamp)
            let minutes = Int(total) / 60
            let seconds = total.truncatingRemainder(dividingBy: 60)
            return String(format: "[%02d:%05.2f]%@", minutes, seconds, line.text)
        }.joined(separator: "\n")
    }
}
